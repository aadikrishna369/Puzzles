// Scans /tools and returns one entry per tool folder (reads each folder's info.txt).
const fs = require('fs');
const path = require('path');

const KEYS = ['name', 'tagline', 'description', 'category', 'icon', 'tags', 'status', 'featured', 'order'];
const THUMBS = ['png', 'jpg', 'jpeg', 'webp', 'svg', 'gif'].map(e => 'assets/thumbnail.' + e);

function parseInfo(text) {
  const out = {};
  let key = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const m = line.match(/^([A-Za-z_]+)\s*:\s*(.*)$/);
    if (m && KEYS.includes(m[1].toLowerCase())) { key = m[1].toLowerCase(); out[key] = m[2].trim(); }
    else if (key) out[key] += ' ' + line;          // wrapped lines continue the previous field
  }
  return out;
}

const titleCase = s => s.replace(/[-_]+/g, ' ').replace(/\b\w/g, c => c.toUpperCase());

function scanTools(root) {
  const dir = path.join(root, 'tools');
  if (!fs.existsSync(dir)) return [];
  const tools = [];
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!ent.isDirectory() || ent.name.startsWith('.') || ent.name.startsWith('_')) continue;
    const folder = path.join(dir, ent.name);
    const infoFile = path.join(folder, 'info.txt');
    const info = fs.existsSync(infoFile) ? parseInfo(fs.readFileSync(infoFile, 'utf8')) : {};
    const status = (info.status || 'live').toLowerCase();
    if (!fs.existsSync(path.join(folder, 'index.html')) && status !== 'soon') continue;
    tools.push({
      slug: ent.name,
      name: info.name || titleCase(ent.name),
      tagline: info.tagline || '',
      description: info.description || '',
      category: info.category || 'General',
      icon: info.icon || '🧩',
      tags: (info.tags || '').split(',').map(t => t.trim()).filter(Boolean),
      status: ['live', 'beta', 'soon'].includes(status) ? status : 'live',
      featured: /^(true|yes|1)$/i.test(info.featured || ''),
      order: Number.isFinite(parseFloat(info.order)) ? parseFloat(info.order) : 999,
      thumbnail: THUMBS.find(t => fs.existsSync(path.join(folder, t))) || null
    });
  }
  return tools.sort((a, b) => (b.featured - a.featured) || (a.order - b.order) || a.name.localeCompare(b.name));
}

function writeManifest(root) {
  const tools = scanTools(root);
  fs.writeFileSync(path.join(root, 'tools', 'manifest.js'),
    '// Auto-generated by build.js / server.js - do not edit.\nwindow.PUZZLES_TOOLS = ' + JSON.stringify(tools, null, 2) + ';\n');
  return tools;
}

module.exports = { scanTools, writeManifest };
